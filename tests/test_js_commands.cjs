'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const {parseDefinitions, expand, complete, inspect} = require('../scripts/js_commands.cjs');
const src = `
/** 两项任务 */
const a=(b,c)=>{ task(b); task(c); };
/** 看状态 */
const b=()=>{ status(); };
/** 查项目 */
const c=project=>{ open(project); };
const auto=(every='60s',threshold=1)=>watch({every,threshold});
`;
const registry=()=>parseDefinitions(src);
test('three arrow shapes',()=>assert.deepEqual([...registry().keys()],['a','b','c','auto']));
test('two args expand in order',()=>assert.deepEqual(expand('a("任务一","任务二")',registry()).steps.map(s=>s.args[0]),['任务一','任务二']));
test('zero arg',()=>assert.equal(expand('b()',registry()).steps[0].command,'status'));
test('single unparenthesized parameter',()=>assert.equal(expand('c("ecom")',registry()).steps[0].args[0],'ecom'));
test('default literal params',()=>assert.equal(expand('auto()',registry()).steps[0].args[0].threshold,1));
test('all results are not executed',()=>assert.equal(expand('b()',registry()).execution,'not_executed'));
test('missing arg fails',()=>assert.throws(()=>expand('a("only")',registry()),/argument/i));
test('extra arg fails',()=>assert.throws(()=>expand('b(1)',registry()),/argument/i));
test('prefix candidates',()=>assert.deepEqual(complete('@continuous-development a',registry()).items.filter(x=>x.source==='custom').map(x=>x.name),['a','auto']));
test('exact bare alias must not execute',()=>assert.equal(inspect('@continuous-development b',registry()).kind,'suggestions'));
test('incomplete call parameter 2',()=>assert.equal(complete('@continuous-development a("x",',registry()).signature.activeParameter,1));
test('comma in a string not arg separator',()=>assert.equal(complete('@continuous-development a("x,y"',registry()).signature.activeParameter,0));
test('nested object comma not arg separator',()=>assert.equal(complete('@continuous-development a({x:1,y:2},',registry()).signature.activeParameter,1));
test('definition preview no persistence',()=>assert.equal(inspect('const foo=x=>open(x);',registry()).registered,false));
test('duplicate names rejected',()=>assert.throws(()=>parseDefinitions('const a=()=>status();const a=x=>open(x);')));
test('reserved builtin cannot be replaced',()=>assert.throws(()=>parseDefinitions('const watch=()=>status();'),/reserved/i));
test('unknown command rejected',()=>assert.throws(()=>parseDefinitions('const z=()=>xxx();'),/unknown/i));
test('placeholder body rejected with error',()=>assert.throws(()=>parseDefinitions('const z=()=>{xxx};')));
test('no eval',()=>assert.throws(()=>parseDefinitions('const z=()=>eval("x");')));
test('no require',()=>assert.throws(()=>parseDefinitions('const z=()=>require("fs");')));
test('no process methods',()=>assert.throws(()=>parseDefinitions('const z=()=>process.exit();')));
test('no top level execution',()=>assert.throws(()=>parseDefinitions('task("x");')));
test('no async',()=>assert.throws(()=>parseDefinitions('const z=async()=>status();')));
test('no loops',()=>assert.throws(()=>parseDefinitions('const z=()=>{while(true){}};')));
test('no computed object keys',()=>assert.throws(()=>parseDefinitions('const z=()=>watch({["every"]:"60s"});')));
test('no proto key',()=>assert.throws(()=>parseDefinitions('const z=()=>watch({__proto__:"x"});')));
test('no arbitrary arg expression',()=>assert.throws(()=>expand('c(process.env)',registry())));
test('no recursively expanding alias',()=>assert.throws(()=>parseDefinitions('const x=()=>y();const y=()=>x();')));
test('template literal safely substituted',()=>{const r=parseDefinitions('const f=x=>task(`处理 ${x}`);');assert.equal(expand('f("bugs")',r).steps[0].args[0],'处理 bugs');});
test('quoted injection remains data',()=>{const p=expand('c("x);watch(); //")',registry());assert.equal(p.steps.length,1);assert.equal(p.steps[0].args[0],'x);watch(); //');});
test('nested aliases expanded',()=>{const r=parseDefinitions('const x=()=>status();const y=()=>{x();open("p");};');assert.equal(expand('y()',r).steps.length,2);});
test('return expression alias',()=>{const r=parseDefinitions('const f=x=>{return open(x);};');assert.equal(expand('f("p")',r).steps.length,1);});
test('code after return rejected',()=>assert.throws(()=>parseDefinitions('const f=()=>{return status();task("x");};')));
test('oversize input rejects',()=>assert.throws(()=>parseDefinitions(' '.repeat(70000))));
test('complete never expands a finished call',()=>assert.equal(complete('a("x","y")',registry()).execution,'not_executed'));
test('invalid cursor rejects',()=>assert.throws(()=>complete('a',registry(),100)));
test('suggest command read only',()=>assert.equal(inspect('suggest("a")',registry()).kind,'suggestions'));
test('commands list read only',()=>assert.equal(inspect('commands()',registry()).kind,'suggestions'));
test('unknown names have no auto-execution fallback',()=>assert.equal(inspect('doesNotExist',registry()).items.length,0));
test('JS object options literal',()=>assert.equal(expand('watch({every:"5m",retry:2})',registry()).steps[0].args[0].retry,2));
test('no broad js code runtime',()=>assert.throws(()=>expand('new Function("return 1")()',registry())));
test('unknown statement nodes fail',()=>assert.throws(()=>parseDefinitions('const f=()=>{let x=1;open(x);};')));
test('command name at middle cursor replaces full token',()=>{const r=complete('@continuous-development always',registry(),25);assert.equal(r.items.find(x=>x.name==='always').replace.end,30);});
test('watch JS options key completion',()=>assert.equal(complete('@continuous-development watch({thr',registry()).items[0].insertText,'threshold: 1'));
test('legacy options key completion',()=>assert.equal(complete('@continuous-development watch(thr',registry()).items[0].insertText,'threshold=1'));
test('watch action string completion',()=>assert.equal(complete('@continuous-development watch("doc',registry()).items[0].insertText,'doctor'));
test('cannot call a parameter as function',()=>assert.throws(()=>parseDefinitions('const x=(task)=>task("x");')));
test('nested quote in template does not execute',()=>{const r=parseDefinitions('const f=x=>task(`fix ${x}`);');assert.equal(expand('f("${process.exit()}")',r).steps[0].args[0],'fix ${process.exit()}');});
